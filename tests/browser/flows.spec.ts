  test('Volga Tatar browser preference localizes sign-in and API validation, and a saved choice overrides it', async ({ browser }) => {
    const context = await browser.newContext({ locale: 'tt-Cyrl-RU', baseURL: 'https://localhost:5188', ignoreHTTPSErrors: true, viewport: { width: 320, height: 700 } })
    const page = await context.newPage()
    try {
      await page.goto('/')
      await expect(page.getByRole('heading', { name: 'Безнең йорт. Ачык мәсьәләләр.' })).toBeVisible()
      await expect(page.locator('html')).toHaveAttribute('lang', 'tt')
      await page.getByRole('button', { name: 'Керү', exact: true }).first().click()
      await page.getByLabel('WhatsApp номеры', { exact: true }).fill('invalid')
      await page.getByRole('button', { name: 'WhatsApp аша код алу' }).click()
      await expect(page.getByRole('alert')).toHaveText('Номерны халыкара форматта кертегез, мәсәлән +1 202 555-0100')
      await page.getByRole('dialog').getByLabel('Интерфейс теле').selectOption('ru')
      await expect(page.getByRole('alert')).toHaveText('Введите номер в международном формате, например +1 202 555-0100')
      await expect(page.getByLabel('Номер WhatsApp', { exact: true })).toHaveValue('invalid')
      await page.getByRole('button', { name: 'Закрыть', exact: true }).click()
      await page.reload()
      await expect(page.getByRole('heading', { name: 'Наш дом. Открытые вопросы.' })).toBeVisible()
      await page.getByLabel('Язык интерфейса').selectOption('tt')
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toEqual(true)
      await page.goto('/missing-page')
      await expect(page.getByRole('heading', { name: 'Бит табылмады' })).toBeVisible()
      await expect(page.locator('html')).toHaveAttribute('lang', 'tt')
    } finally { await context.close() }
  })

  test('an unsupported browser language falls back to Russian even when language storage is unavailable', async ({ browser }) => {
    const context = await browser.newContext({ locale: 'en-US', baseURL: 'https://localhost:5188', ignoreHTTPSErrors: true })
    const page = await context.newPage()
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.addInitScript(() => {
      Object.defineProperty(Storage.prototype, 'getItem', { value() { throw new DOMException('Disabled', 'SecurityError') } })
      Object.defineProperty(Storage.prototype, 'setItem', { value() { throw new DOMException('Disabled', 'SecurityError') } })
    })
    try {
      await page.goto('/')
      await expect(page.getByRole('heading', { name: 'Наш дом. Открытые вопросы.' })).toBeVisible()
      await page.getByLabel('Язык интерфейса').selectOption('tt')
      await expect(page.getByRole('heading', { name: 'Безнең йорт. Ачык мәсьәләләр.' })).toBeVisible()
      expect(errors).toEqual([])
    } finally { await context.close() }
  })
